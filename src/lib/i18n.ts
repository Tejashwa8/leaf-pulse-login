const STORAGE_KEY = "leafrx_lang";
const EVENT = "leafrx:lang-change";

export function getLang(): LangCode {
  if (typeof localStorage === "undefined") return "en";
  const v = localStorage.getItem(STORAGE_KEY) as LangCode | null;
  return v && dicts[v] ? v : "en";
}

export function setLang(code: LangCode) {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {}
  if (typeof document !== "undefined") {
    document.documentElement.lang = code;
    document.documentElement.dir = code === "ur" ? "rtl" : "ltr";
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent(EVENT, { detail: code }));
  }
}

export function useLang(): [LangCode, (c: LangCode) => void, (k: string) => string] {
  const [lang, setLangState] = useState<LangCode>("en");
  useEffect(() => {
    setLangState(getLang());
    const onChange = (e: Event) => {
      const code = (e as CustomEvent<LangCode>).detail || getLang();
      setLangState(code);
    };
    window.addEventListener(EVENT, onChange);
    // Initialize html lang/dir
    const init = getLang();
    document.documentElement.lang = init;
    document.documentElement.dir = init === "ur" ? "rtl" : "ltr";
    return () => window.removeEventListener(EVENT, onChange);
  }, []);
  const t = (key: string) => dicts[lang]?.[key] ?? en[key] ?? key;
  const change = (c: LangCode) => setLang(c);
  return [lang, change, t];
}
